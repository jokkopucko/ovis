/**
 * Claude Code's status line, wrapped on request so the five-hour and weekly limits it is handed also
 * land in ~/.herdr/statusline-last.json (server/statusline.ts reads them for Subscription usage).
 * Nothing turns this on by itself: Settings -> Subscription usage asks for it through
 * POST /api/usage/statusline (handleStatuslineRequest in server/usage.ts), which takes only on or off.
 *
 * It adds only its own directory, `herdr-statusline/` in Claude's config directory
 * (CLAUDE_CONFIG_DIR, else ~/.claude), and points `statusLine.command` in that directory's
 * settings.json at the wrapper there (creating settings.json when Claude has none yet). The wrapper
 * runs the command that was set before exactly as Claude ran it (`sh -c`, arguments and all), so the
 * line Claude draws stays the same; where no status line was set it draws none. Only the
 * `statusLine` member of settings.json is edited, in place, so the rest of the file keeps its bytes.
 *
 * Removing it writes settings.json back byte for byte when nothing else in it changed since the
 * install (deleting it when the install created it), and otherwise puts back only the status line
 * it replaced (or its absence). It then deletes the installer's own files and the captured payload.
 */
import { createHash, randomUUID } from "node:crypto";
import { chmodSync, existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, realpathSync, renameSync, rmdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";

const BANNER = "# Generated by the herdr web UI's status-line installer (server/statusline-install.ts); do not edit.";
const KEY = "statusLine";

/** A refusal whose message is safe to show anywhere: it never quotes settings.json or a command in it. */
export class StatuslineInstallError extends Error {}
const WRAPPER = "herdr-statusline/statusline-tee.sh";
/** the only files the installer writes in its directory, and so the only ones --remove deletes */
const OWN_FILES = ["statusline-tee.sh", "statusline-capture.ts", "install.json"] as const;
/** what a write of one of them cut short (a killed install) leaves behind; see writeAtomically */
const LEFTOVER = /^\.(?:statusline-tee\.sh|statusline-capture\.ts|install\.json)\.\d+\.[0-9a-f-]{36}\.tmp$/;

interface InstallRecord {
  /** settings.json as it was before the install (null: there was none), and as the install wrote it */
  original: string | null;
  installed: string;
  /** the `statusLine` value's own text before the install; null where there was none */
  statusLine: string | null;
  command: string;
}

const shellQuote = (value: string): string => (/^[\w./:@%+=,-]+$/.test(value) ? value : `'${value.replaceAll("'", `'\\''`)}'`);
const isObject = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);
const commandOf = (value: unknown): string | null => (isObject(value) && typeof value["command"] === "string" ? value["command"] : null);

/**
 * The words a POSIX shell would split `command` into, with quotes and backslashes taken off and a
 * leading unquoted `~/` expanded; nothing is run. Enough to find a path however it is quoted.
 */
function shellWords(command: string, home: string): string[] {
  const words: string[] = [];
  let word: string | null = null;
  for (let at = 0; at < command.length; at++) {
    const char = command[at]!;
    if (/\s/.test(char)) { if (word !== null) words.push(word); word = null; continue; }
    if (char === "#" && word === null) {
      const end = command.indexOf("\n", at);
      at = end === -1 ? command.length : end;
      continue;
    }
    word ??= "";
    if (char === "'") {
      const end = command.indexOf("'", at + 1);
      word += command.slice(at + 1, end === -1 ? undefined : end);
      at = end === -1 ? command.length : end;
    } else if (char === '"') {
      for (at++; at < command.length && command[at] !== '"'; at++) {
        word += command[at] === "\\" && /["\\$`]/.test(command[at + 1] ?? "") ? command[++at] : command[at];
      }
    } else if (char === "\\") {
      word += command[++at] ?? "";
    } else if (char === "~" && word === "" && command[at + 1] === "/") {
      word += home;
    } else {
      word += char;
    }
  }
  if (word !== null) words.push(word);
  return words;
}

/** Whether `path` is the wrapper at `tee`, however it is spelled (a symlinked config dir, `/./`, `//`). */
function runsWrapper(path: string, tee: string): boolean {
  try { return realpathSync(path) === realpathSync(tee); } catch { return false; }
}

/** Whether `command` names a wrapper of this installer: any copy by name, or this one however spelled. */
const runsAWrapper = (command: string, tee: string, home: string): boolean =>
  command.includes(WRAPPER) || shellWords(command, home).some((word) => word !== "" && runsWrapper(word, tee));

/**
 * Whether --remove may replace `command`: one the installer wrote (its wrapper's name in it), or one
 * that runs the wrapper however spelled, as its command or through a shell. A command that only
 * mentions the path in its arguments (`printf <path>`) is the user's own, and stays.
 */
function ownsCommand(command: string, tee: string, home: string): boolean {
  if (command.includes(WRAPPER)) return true;
  const words = shellWords(command, home);
  const runner = /^(?:exec|sh|bash|dash|zsh|ksh)$/.test(basename(words[0] ?? "")) ? 1 : 0;
  return words[runner] !== undefined && runsWrapper(words[runner], tee);
}

export interface StatuslineInstallOptions {
  /** the home whose ~/.herdr holds the captured payload, and ~/.claude when no config dir is set */
  home: string;
  /** Claude's CLAUDE_CONFIG_DIR, as the server's own environment names it */
  configDir?: string | undefined;
  /** the Bun that runs the capture helper; this server's own by default */
  bunPath?: string;
}

function locations(options: StatuslineInstallOptions) {
  const configured = options.configDir?.trim();
  const configDir = configured ? resolve(configured) : join(options.home, ".claude");
  const own = join(configDir, "herdr-statusline");
  const tee = join(own, "statusline-tee.sh");
  return {
    configDir,
    settings: join(configDir, "settings.json"),
    own,
    tee,
    capture: join(own, "statusline-capture.ts"),
    record: join(own, "install.json"),
    command: shellQuote(tee),
    payload: join(options.home, ".herdr", "statusline-last.json"),
    bun: options.bunPath ?? process.execPath,
    home: options.home,
  };
}

interface Member { start: number; valueStart: number; valueEnd: number }

/**
 * Where each top-level member of a JSON object text sits, so one member can be swapped or dropped
 * without reformatting the rest. The text must already have passed JSON.parse.
 */
function members(text: string): { found: Map<string, Member>; order: Member[]; close: number } {
  let at = 0;
  const space = () => { while (" \t\r\n".includes(text[at] ?? "x")) at++; };
  const string = (): string => {
    const start = at++;
    while (text[at] !== '"') at += text[at] === "\\" ? 2 : 1;
    at++;
    return JSON.parse(text.slice(start, at)) as string;
  };
  const value = () => {
    if (text[at] === '"') { string(); return; }
    if (text[at] !== "{" && text[at] !== "[") {
      while (at < text.length && !" \t\r\n,}]".includes(text[at]!)) at++;
      return;
    }
    let depth = 0;
    do {
      if (text[at] === '"') { string(); continue; }
      if (text[at] === "{" || text[at] === "[") depth++;
      else if (text[at] === "}" || text[at] === "]") depth--;
      at++;
    } while (depth > 0);
  };
  const found = new Map<string, Member>();
  const order: Member[] = [];
  space();
  at++;
  space();
  while (text[at] !== "}") {
    const start = at;
    const key = string();
    space();
    at++;
    space();
    const valueStart = at;
    value();
    const member = { start, valueStart, valueEnd: at };
    found.set(key, member); // JSON.parse keeps the last of a repeated key, and so does this
    order.push(member);
    space();
    if (text[at] === ",") { at++; space(); }
  }
  return { found, order, close: at };
}

/** `text` with its top-level `statusLine` set to the JSON text `value`, or dropped where it is null. */
function withStatusLine(text: string, value: string | null): string {
  const { found, order, close } = members(text);
  const member = found.get(KEY);
  if (member && value !== null) return text.slice(0, member.valueStart) + value + text.slice(member.valueEnd);
  if (member) {
    const index = order.indexOf(member);
    if (index > 0) return text.slice(0, order[index - 1]!.valueEnd) + text.slice(member.valueEnd);
    const next = order[1];
    return next ? text.slice(0, member.start) + text.slice(next.start) : text.slice(0, text.lastIndexOf("{", member.start) + 1) + text.slice(close);
  }
  if (value === null) return text;
  const last = order.at(-1);
  if (!last) return `${text.slice(0, close).trimEnd()}\n  "${KEY}": ${value}\n${text.slice(close)}`;
  const lineStart = text.lastIndexOf("\n", order[0]!.start) + 1;
  const indent = text.slice(lineStart, order[0]!.start);
  const separator = /^[ \t]*$/.test(indent) && lineStart > 0 ? `\n${indent}` : " ";
  return `${text.slice(0, last.valueEnd)},${separator}"${KEY}": ${value}${text.slice(last.valueEnd)}`;
}

const isMissing = (error: unknown): boolean => error !== null && typeof error === "object" && "code" in error && error.code === "ENOENT";

/** Write through a temporary file and a rename, so a failed write leaves the old file whole. */
function writeAtomically(path: string, content: string, mode: number): void {
  const temporary = join(dirname(path), `.${basename(path)}.${process.pid}.${randomUUID()}.tmp`);
  try {
    writeFileSync(temporary, content, { flag: "wx", mode });
    chmodSync(temporary, mode);
    renameSync(temporary, path);
  } finally {
    rmSync(temporary, { force: true });
  }
}

/** settings.json is often a link into a dotfiles checkout: the file it points at is the one rewritten. */
function writeSettings(path: string, content: string): void {
  const target = realpathSync(path);
  writeAtomically(target, content, statSync(target).mode & 0o777);
}

/**
 * The installer's directory is used only while it holds nothing but the installer's own regular
 * files: a link there could point a write anywhere, and anything else there is the user's.
 */
function checkOwnDirectory(own: string): "missing" | "owned" {
  let entry;
  try { entry = lstatSync(own); } catch (error) { if (isMissing(error)) return "missing"; throw error; }
  if (!entry.isDirectory()) throw new StatuslineInstallError(`${own} is not a directory this installer made; move it away first`);
  for (const name of readdirSync(own)) {
    const file = lstatSync(join(own, name));
    if (LEFTOVER.test(name) && file.isFile()) { rmSync(join(own, name)); continue; }
    if (!(OWN_FILES as readonly string[]).includes(name) || !file.isFile()) throw new StatuslineInstallError(`${own} holds ${name}, which this installer did not write; move it away first`);
  }
  const tee = join(own, "statusline-tee.sh");
  if (existsSync(tee) && !readFileSync(tee, "utf8").includes(BANNER)) throw new StatuslineInstallError(`${tee} was not written by this installer; move it away first`);
  return "owned";
}

/** settings.json as text and value; a config directory without one is read as `{}` that is not there yet. */
function readSettings(path: string): { text: string | null; value: Record<string, unknown> } {
  if (!existsSync(path)) {
    // a link to a file not there yet (a dotfiles checkout not set up) is the user's, not an absent file
    if (lstatSync(path, { throwIfNoEntry: false })?.isSymbolicLink()) throw new StatuslineInstallError(`${path} links to a file that is not there; fix the link first`);
    return { text: null, value: {} };
  }
  const text = readFileSync(path, "utf8");
  const value: unknown = JSON.parse(text);
  if (!isObject(value)) throw new StatuslineInstallError(`${path} does not hold a JSON object`);
  return { text, value };
}

function wrapper(previous: string | null, capture: string, bun: string): string {
  const lines = [
    "#!/bin/sh",
    BANNER,
    "# Keeps the limits Claude Code hands its status line where the herdr web UI reads them",
    "# (~/.herdr/statusline-last.json), then runs the status line that was set before, unchanged.",
    "# Never inside itself: a wrapper that ended up wrapping a wrapper would run forever.",
    '[ -n "${HERDR_STATUSLINE_TEE:-}" ] && exit 0',
    "export HERDR_STATUSLINE_TEE=1",
    "# The x keeps the payload's trailing newlines, which $( ) would strip.",
    "payload=$(cat; printf x)",
    "payload=${payload%x}",
    "# The capture runs on its own, so the line is drawn and the wrapper ends without waiting for it.",
    `(umask 077; printf '%s' "$payload" | ${shellQuote(bun)} ${shellQuote(capture)}) >/dev/null 2>&1 &`,
  ];
  if (previous !== null) lines.push(`printf '%s' "$payload" | sh -c ${shellQuote(previous)}`);
  return `${lines.join("\n")}\n`;
}

export interface StatuslineInstallState {
  /** Claude's settings run this installer's wrapper, and its record is there to undo it */
  installed: boolean;
  /** the wrapper is a POSIX shell script: not on Windows */
  supported: boolean;
}

export function statuslineInstallState(options: StatuslineInstallOptions): StatuslineInstallState {
  if (process.platform === "win32") return { installed: false, supported: false };
  const where = locations(options);
  try {
    const command = commandOf(readSettings(where.settings).value[KEY]);
    return { installed: existsSync(where.record) && command !== null && ownsCommand(command, where.tee, where.home), supported: true };
  } catch {
    return { installed: false, supported: true };
  }
}

const CAPTURE_SOURCE = (): string => readFileSync(new URL("./statusline-capture.ts", import.meta.url), "utf8");

const isCode = (error: unknown, code: string): boolean => error !== null && typeof error === "object" && "code" in error && error.code === code;

/** Whether the process a lock's owner token (`<pid>:<uuid>`) names still runs on this PC. */
function holderRuns(token: string): boolean {
  const pid = Number(token.split(":")[0]);
  try { process.kill(pid, 0); return true; } catch (error) { return isCode(error, "EPERM"); }
}

/**
 * One change at a time, across processes too (two servers on one home): an install and a removal
 * that interleave could leave settings.json running a wrapper the other just deleted. The lock is
 * published whole (built aside with its owner, then renamed into place, which replaces only an empty
 * directory: no change ever holds one), names its holder, is taken
 * over only from a holder that is gone, and is released only by its own holder. A live holder is
 * never overruled: a lock left by a crashed server whose pid another process now has stays until
 * removed by hand, which the refusal names.
 */
function locked<T>(configDir: string, change: () => T): T {
  const lock = join(configDir, ".herdr-statusline.lock");
  const ownerOf = (dir: string): string | null => { try { return readFileSync(join(dir, "owner"), "utf8"); } catch { return null; } };
  const token = `${process.pid}:${randomUUID()}`;
  const busy = () => new StatuslineInstallError(`another change to Claude's status line is in progress; try again in a moment (if none is, delete ${lock})`);
  const take = (): boolean => {
    const built = `${lock}.${process.pid}.${randomUUID()}.new`;
    mkdirSync(built);
    writeFileSync(join(built, "owner"), token, { mode: 0o600 });
    try { renameSync(built, lock); return true; }
    catch (error) {
      rmSync(built, { recursive: true, force: true });
      // held (a lock with its owner), or not a directory this can replace (a link): either way, not ours
      if (isCode(error, "EEXIST") || isCode(error, "ENOTEMPTY") || isCode(error, "ENOTDIR")) return false;
      throw error;
    }
  };
  if (!take()) {
    const entry = lstatSync(lock, { throwIfNoEntry: false });
    const seen = ownerOf(lock);
    // a token is whole once published; anything else (a link, no owner, a holder still running) is busy
    if (!entry?.isDirectory() || seen === null || !/^\d+:[0-9a-f-]{36}$/.test(seen) || holderRuns(seen)) throw busy();
    // moved aside, then checked: only the lock judged abandoned is removed, never one taken since
    const aside = `${lock}.${process.pid}.${randomUUID()}.old`;
    try { renameSync(lock, aside); } catch { throw busy(); }
    if (ownerOf(aside) !== seen) {
      try { renameSync(aside, lock); } catch { /* a third change holds it now; the moved one stays aside */ }
      throw busy();
    }
    rmSync(aside, { recursive: true, force: true });
    if (!take()) throw busy();
  }
  try {
    return change();
  } finally {
    if (ownerOf(lock) === token) rmSync(lock, { recursive: true, force: true });
  }
}

export function installStatusline(options: StatuslineInstallOptions): string {
  const where = locations(options);
  if (process.platform !== "win32" && !existsSync(where.configDir)) throw new StatuslineInstallError(`${where.configDir} is missing: is Claude Code installed on this PC?`);
  return process.platform === "win32" ? installUnlocked(options) : locked(where.configDir, () => installUnlocked(options));
}

function installUnlocked(options: StatuslineInstallOptions): string {
  if (process.platform === "win32") throw new StatuslineInstallError("the status-line wrapper is a POSIX shell script; Windows is not supported");
  const where = locations(options);
  if (!existsSync(where.configDir)) throw new StatuslineInstallError(`${where.configDir} is missing: is Claude Code installed on this PC?`);
  const { text, value } = readSettings(where.settings);
  const current = value[KEY];
  const command = commandOf(current);
  if (command !== null && runsAWrapper(command, where.tee, where.home)) {
    const words = shellWords(command, where.home);
    if (existsSync(where.record) && words.length === 1 && runsWrapper(words[0]!, where.tee)) return `already installed: ${where.settings} runs ${command}`;
    throw new StatuslineInstallError(`${where.settings} already runs a status-line wrapper of this installer: turn it off with the CLAUDE_CONFIG_DIR it was turned on with, or set statusLine yourself`);
  }
  checkOwnDirectory(where.own);

  const previous = isObject(current) && typeof current["command"] === "string" && current["command"].trim() !== "" ? current["command"] : null;
  const statusLine = JSON.stringify({ ...(isObject(current) ? current : {}), type: "command", command: where.command });
  const member = text === null ? undefined : members(text).found.get(KEY);
  const installed = text === null ? `{\n  "${KEY}": ${statusLine}\n}\n` : withStatusLine(text, statusLine);
  const record: InstallRecord = { original: text, installed, statusLine: member && text !== null ? text.slice(member.valueStart, member.valueEnd) : null, command: where.command };

  mkdirSync(where.own, { recursive: true, mode: 0o700 });
  chmodSync(where.own, 0o700);
  writeAtomically(where.capture, CAPTURE_SOURCE(), 0o600);
  writeAtomically(where.tee, wrapper(previous, where.capture, where.bun), 0o700);
  // the record goes before settings.json: an install cut short still leaves what removing it needs
  writeAtomically(where.record, `${JSON.stringify(record, null, 2)}\n`, 0o600);
  if (text === null) writeAtomically(where.settings, installed, 0o600);
  else writeSettings(where.settings, installed);
  return `installed: ${where.settings} runs ${where.command}, which keeps the limits in ~/.herdr/statusline-last.json`
    + (previous === null ? " (no status line was set, so it draws none)" : ` and then runs ${previous}`);
}

export function removeStatusline(options: StatuslineInstallOptions): string {
  const where = locations(options);
  if (!existsSync(where.configDir)) return `nothing to remove: ${where.configDir} is not there`;
  return locked(where.configDir, () => removeUnlocked(options));
}

function removeUnlocked(options: StatuslineInstallOptions): string {
  const where = locations(options);
  let entry;
  try { entry = lstatSync(where.own); } catch (error) { if (isMissing(error)) return `nothing to remove: ${where.own} is not there`; throw error; }
  // a link here could point the deletions below anywhere
  if (!entry.isDirectory()) throw new StatuslineInstallError(`${where.own} is not the directory this installer made (a link?); move it away first`);
  if (existsSync(where.record) && !lstatSync(where.record).isFile()) throw new StatuslineInstallError(`${where.record} is not a file this installer wrote; move it away first`);
  let outcome: string;
  const recorded = existsSync(where.record);
  if (!recorded) {
    // an install cut short before its record was written never touched settings.json
    outcome = `left ${where.settings} as it is: the install never reached it`;
  } else {
    const record = JSON.parse(readFileSync(where.record, "utf8")) as InstallRecord;
    const { text, value } = readSettings(where.settings);
    if (text !== null && text === record.installed) {
      if (record.original === null) rmSync(where.settings);
      else writeSettings(where.settings, record.original);
      outcome = record.original === null ? `deleted ${where.settings}, which the install created` : `put ${where.settings} back as it was`;
    } else if (text !== null && ownsCommand(commandOf(value[KEY]) ?? "", where.tee, where.home)) {
      writeSettings(where.settings, withStatusLine(text, record.statusLine));
      outcome = `put back the status line in ${where.settings}; its other changes since the install stay`;
    } else {
      outcome = `left ${where.settings} as it is: its status line was changed since the install`;
    }
  }
  const removeFile = (path: string) => {
    try {
      if (!lstatSync(path).isFile()) return;
      // a wrapper without the banner is not this installer's, even where its name is; without a record,
      // a capture helper is this installer's only when it is the one it ships, byte for byte
      if (path === where.tee && !readFileSync(path, "utf8").includes(BANNER)) return;
      if (path === where.capture && !recorded && readFileSync(path, "utf8") !== CAPTURE_SOURCE()) return;
      rmSync(path);
    } catch (error) { if (!isMissing(error)) throw error; }
  };
  for (const name of [...OWN_FILES, ...readdirSync(where.own).filter((name) => LEFTOVER.test(name))]) removeFile(join(where.own, name));
  removeFile(where.payload);
  const contexts = join(where.home, ".herdr", "statusline-context");
  try {
    // Other Claude profiles share the home; their context captures must survive this removal.
    if (lstatSync(contexts).isDirectory()) {
      const profile = createHash("sha256").update(realpathSync(where.configDir)).digest("hex");
      for (const name of readdirSync(contexts)) {
        if (!/^[a-zA-Z0-9-]{1,128}\.json$/.test(name)) continue;
        const path = join(contexts, name);
        if (!lstatSync(path).isFile()) continue;
        let captured;
        try { captured = JSON.parse(readFileSync(path, "utf8")); } catch { continue; }
        if (captured?._herdr?.profile === profile) rmSync(path);
      }
      if (readdirSync(contexts).length === 0) rmdirSync(contexts);
    }
  } catch (error) { if (!isMissing(error)) throw error; }
  const left = readdirSync(where.own);
  if (left.length > 0) return `removed: ${outcome}, and deleted the installer's files and ${where.payload}; ${where.own} stays for what else is in it (${left.join(", ")})`;
  rmdirSync(where.own);
  return `removed: ${outcome}, and deleted ${where.own} and ${where.payload}`;
}
